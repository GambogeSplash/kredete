// Shared by `npm run types` (writes types.d.ts) and `npm run check` (detects drift).
import { existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const DEFAULT_OPENAPI = resolve(ROOT, '../broth-service/openapi/openapi.json');

/** The OpenAPI document to read: BROTH_OPENAPI, or the sibling broth-service checkout. */
export function openapiPath() {
  return resolve(process.env.BROTH_OPENAPI || DEFAULT_OPENAPI);
}

/** Whether the OpenAPI document is available on this machine. */
export function openapiAvailable() {
  return existsSync(openapiPath());
}

/**
 * Renders the TypeScript declarations for the OpenAPI document at `path`.
 * @param {string} path
 * @returns {Promise<string>}
 */
export async function generateTypes(path) {
  const ast = await openapiTS(pathToFileURL(path));
  const header =
    '// Generated by `npm run types` from broth-service openapi/openapi.json. Do not edit.\n' +
    '// Regenerate after every API change (docs/client-types.md in broth-service).\n\n';
  return header + astToString(ast);
}
